def scale(v):
    # out = round((2048-AMP) + v * 2*AMP / 4095), 四舍五入用整数实现
    # 即 0→1648, 2048→2048, 4095→2448
    return (2 * AMP * v + 4095 // 2 + (2048 - AMP) * 4095) // 4095

