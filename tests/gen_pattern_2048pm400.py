def fmt(name, arr):
    lines = ["static const uint16_t %s[%d] = {" % (name, N)]
    for i in range(0, N, 16):
        chunk = arr[i:i + 16]
        lines.append("    " + "".join("%5d," % v for v in chunk))
    lines[-1] = lines[-1].rstrip(",")
    lines.append("};")
    return "\n".join(lines)

